$scheduleId = (int) ($_GET['schedule_id'] ?? 0);
$sort = $_GET['sort'] ?? '';
$dir = ($_GET['dir'] ?? 'asc') === 'desc' ? 'desc' : 'asc';

if ($scheduleId <= 0) {
    die("No schedule specified.");
}

$stmt = mysqli_prepare($conn, "SELECT title, event_date, start_time, end_time, schedule_type FROM schedules WHERE schedule_id = ?");
mysqli_stmt_bind_param($stmt, "i", $scheduleId);
mysqli_stmt_execute($stmt);
$result = mysqli_stmt_get_result($stmt);
$schedule = $result ? $result->fetch_assoc() : null;
mysqli_stmt_close($stmt);

if (!$schedule) {
    die("Schedule not found.");
}

$attendees = getPresentAttendees($conn, $scheduleId, $sort, $dir);

$reportTitle = "Schedule Attendance";
$reportSubtitle = $schedule['title'];

$sortLabels = ['brand_name' => 'Brand', 'dealership_name' => 'Dealership'];
$sortedBy = isset($sortLabels[$sort])
    ? $sortLabels[$sort] . ' (' . ($dir === 'desc' ? 'Z-A' : 'A-Z') . ')'
    : null;

$tableHeaders = ["Learner", "Brand", "Dealership", "Status"];
$tableRows = [];

foreach ($attendees as $a) {
    $tableRows[] = [
        $a['first_name'] . ' ' . $a['last_name'],
        $a['brand_name'] ?: '—',
        $a['dealership_name'] ?: '—',
        $a['attendance_status']
    ];
}

